# Introspection sources
# ---------------------------------------------------------------------------

def introspect_opencode(root: Path) -> list[str]:
    """Union of MCP server ids from opencode.jsonc / .opencode.json / .mcp.json."""
    servers: list[str] = []
    for fname in ("opencode.jsonc", ".opencode.json", ".mcp.json"):
        p = root / fname
        if not p.is_file():
            continue
        try:
            data = _load_jsonc(p)
        except Exception as exc:
            logger.warning("Failed to parse %s: %s", p, exc)
            continue
        mcp = data.get("mcpServers") or data.get("mcp") or {}
        if isinstance(mcp, dict):
            servers.extend(mcp.keys())
    seen: set[str] = set()
    out: list[str] = []
    for s in servers:
        if s not in seen:
            seen.add(s)
            out.append(s)
    return out


def introspect_skills(root: Path) -> list[dict[str, str]]:
    """Scan known skill dirs for name + description (markdown frontmatter)."""
    skills: list[dict[str, str]] = []
    seen: set[str] = set()
    search_dirs = [
        root / ".claude" / "skills",
        root / "skills" / "superpowers" / "skills",
    ]
    for d in search_dirs:
        if not d.is_dir():
            continue
        entries = list(d.glob("*.md")) + list(d.glob("*/SKILL.md"))
        for path in entries:
            meta = _parse_skill_frontmatter(path)
            name = meta.get("name") or path.stem
            if name in seen:
                continue
            seen.add(name)
            skills.append({"name": name, "description": meta.get("description", "")})
    return skills


def _parse_skill_frontmatter(path: Path) -> dict[str, str]:
    try:
        text = path.read_text()
    except Exception:
        return {}
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    if end == -1:
        return {}
    block = text[3:end].strip()
    meta: dict[str, str] = {}
    for line in block.splitlines():
        if ":" not in line:
            continue
        key, _, val = line.partition(":")
        meta[key.strip()] = val.strip().strip('"').strip("'")
    return meta


def introspect_repo(root: Path) -> list[str]:
    """Curated top-level package list that makes up the system."""
    packages: list[str] = []
    for entry in sorted(root.iterdir()):
        if not entry.is_dir() or entry.name.startswith("."):
            continue
        if (entry / "__init__.py").is_file() or (entry / "pyproject.toml").is_file():
            packages.append(entry.name)
    return packages


async def introspect_backend(
    http_client: httpx.AsyncClient | None = None,
) -> tuple[str, str, dict[str, bool]]:
    """Determine the live inference backend from config + health probes."""
    if settings.opencode_go_api_url:
        backend = f"opencode-go (hosted {settings.model_id})"
    elif settings.vllm_primary_url:
        backend = f"vLLM local ({settings.model_id})"
    else:
        backend = settings.model_id or "unknown"
    model = settings.model_id

    health: dict[str, bool] = {}

    async def probe(url: str, key: str) -> None:
        try:
            if http_client is not None:
                r = await http_client.get(url, timeout=settings.probe_timeout_s)
            else:
                async with httpx.AsyncClient(timeout=settings.probe_timeout_s) as c:
                    r = await c.get(url)
            health[key] = r.status_code < 500
        except Exception:
            health[key] = False

    if settings.vllm_health_url:
        await probe(settings.vllm_health_url, "vllm")
    if settings.opencode_go_api_url:
        await probe(settings.opencode_go_api_url, "opencode-go")

    return backend, model, health



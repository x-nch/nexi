"""Auto-generate the nexi persona overlay from live sources of truth.

Sources (the "everything in XNCHSYSTEMS" inventory):
- ``nexi/infra/discovery``                → hosts, services, live health probes
- ``xnch GET /nexi/tools`` + mcp config   → native + bridged tool inventory
- ``nexi/config.py`` (live values)        → active inference backend + model
- ``opencode.jsonc`` / ``.opencode.json`` / ``.mcp.json`` → OpenCode MCP servers
- ``skills`` dirs (``.claude/skills``, ``skills/superpowers/skills``) → agent skills
- repo topography                        → packages that make up the system

Unlike the capability overlay, this generator produces the *persona narrative itself*:
it fills the ``persona.yaml`` template (which holds only voice/identity constants and
``{placeholders}``) with a live ``self_model`` so no factual claim is ever hardcoded.

The overlay is written atomically (tmp+rename) and only when content changes, so
``nexi/character/prompt_loader.load_persona()`` keeps rendering a stable merged view.
"""

from __future__ import annotations

import json
import logging
import re
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import httpx
import yaml

from nexi.config import settings
from nexi.adapters.model_router import available_models, routing_summary
from nexi.infra.discovery import (
    InfraSnapshot,
    build_snapshot,
    probe_services,
)

logger = logging.getLogger(__name__)

_HEADER = "# AUTO-GENERATED by nexi/character/persona_builder.py — do not edit."

# Repo root: nexi/character/persona_builder.py -> parents[2] == xnchSystems/
_REPO_ROOT = Path(__file__).resolve().parents[2]


@dataclass
class SelfModel:
    """Structured live self-description of the whole workspace."""

    inference_backend: str = ""
    active_model: str = ""
    hosts: dict[str, str] = field(default_factory=dict)
    services: list[dict[str, Any]] = field(default_factory=list)
    mcp_servers: list[str] = field(default_factory=list)
    skills: list[dict[str, str]] = field(default_factory=list)
    tool_count: int = 0
    repo_packages: list[str] = field(default_factory=list)
    healthy: list[str] = field(default_factory=list)
    down: list[str] = field(default_factory=list)
    backend_health: dict[str, bool] = field(default_factory=dict)
    available_models: list[str] = field(default_factory=list)
    model_routing: str = ""


@dataclass
class PersonaResult:
    self_model: SelfModel
    persona_text: str = ""
    changed: bool = False
    error: str | None = None


class PersonaGenerationError(Exception):
    """Raised when the persona template cannot be rendered against the self-model."""


# ---------------------------------------------------------------------------
# Tolerant JSONC parsing (for opencode.jsonc which carries comments + trailing
# commas and `//` inside URL strings).
# ---------------------------------------------------------------------------

def _strip_jsonc(text: str) -> str:
    out: list[str] = []
    i, n = 0, len(text)
    in_str = False
    esc = False
    while i < n:
        c = text[i]
        if in_str:
            out.append(c)
            if esc:
                esc = False
            elif c == "\\":
                esc = True
            elif c == '"':
                in_str = False
            i += 1
            continue
        if c == '"':
            in_str = True
            out.append(c)
            i += 1
            continue
        if c == "/" and i + 1 < n and text[i + 1] == "/":
            while i < n and text[i] != "\n":
                i += 1
            continue
        if c == "/" and i + 1 < n and text[i + 1] == "*":
            i += 2
            while i + 1 < n and not (text[i] == "*" and text[i + 1] == "/"):
                i += 1
            i += 2
            continue
        out.append(c)
        i += 1
    stripped = "".join(out)
    # Drop trailing commas before } or ]
    stripped = re.sub(r",(\s*[}\]])", r"\1", stripped)
    return stripped


def _load_jsonc(path: Path) -> dict[str, Any]:
    raw = path.read_text()
    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        return json.loads(_strip_jsonc(raw))


